import fs from "node:fs";
import assert from "node:assert/strict";

const html = fs.readFileSync("index.html", "utf8");
const pointsMatch = html.match(/const monacoPoints=\\[([\\s\\S]*?)\\n\\];/);
assert.ok(pointsMatch, "Geographic Monaco centreline must exist");
const points = [...pointsMatch[1].matchAll(/\\[\\s*(-?[\\d.]+)\\s*,\\s*(-?[\\d.]+)\\s*,\\s*(-?[\\d.]+)\\s*\\]/g)]
  .map(m => [Number(m[1]), Number(m[2]), Number(m[3])]);
assert.ok(points.length >= 400, `Expected the full mapped road trace, found ${points.length} points`);
assert.deepEqual(points[0], [0, 0, 0], "Monaco lap must begin at the mapped start/finish GPS point");
let polylineLength = 0;
for (let i = 1; i < points.length; i++) polylineLength += Math.hypot(points[i][0]-points[i-1][0],points[i][2]-points[i-1][2]);
polylineLength += Math.hypot(points[0][0]-points.at(-1)[0],points[0][2]-points.at(-1)[2]);
assert.ok(polylineLength > 3300 && polylineLength < 3340, `Mapped Monaco road should be approximately 3.323 km, got ${polylineLength.toFixed(1)}m`);
const xs=points.map(p=>p[0]),zs=points.map(p=>p[2]);
assert.ok(Math.max(...xs)-Math.min(...xs)>730 && Math.max(...xs)-Math.min(...xs)<750,"Mapped Monaco east-west extent must match the real street circuit");
assert.ok(Math.max(...zs)-Math.min(...zs)>960 && Math.max(...zs)-Math.min(...zs)<990,"Mapped Monaco north-south extent must match the real street circuit");
assert.match(html,/OpenStreetMap circuit-road relation/);
assert.match(html,/const MONACO_PUBLISHED_LENGTH_M=3337;/);
assert.match(html,/const MONACO_BASE_LENGTH_M=new THREE\\.CatmullRomCurve3/);
assert.match(html,/const harborCenter=\\{x:303,z:-309\\}/);
assert.match(html,/const sea=new THREE\\.Mesh\\(new THREE\\.PlaneGeometry\\(360,340,1,1\\),seaMat\\)/);
assert.match(html,/const tunnelStart=790,tunnelEnd=985/);
assert.match(html,/function loadMonacoWorld\\(\\)/);
assert.match(html,/monacoWorld\\.visible=next==="monaco"/);
assert.match(html,/monacoWorld\\.visible=prevTrack==="monaco"/);
const tunnelMatch=html.match(/const tunnelStart=(\\d+),tunnelEnd=(\\d+);/);
assert.ok(tunnelMatch,"Monaco tunnel bounds must be defined");
const tunnelLength=(Number(tunnelMatch[2])-Number(tunnelMatch[1]))/1600*3337;
assert.ok(tunnelLength>=350&&tunnelLength<=450,`Monaco tunnel should cover about 400m, got ${tunnelLength.toFixed(0)}m`);
console.log(`Monaco geographic checks passed: ${points.length} mapped points, ${polylineLength.toFixed(0)}m source trace, 3.337 km scaled lap, correctly placed Port Hercule and tunnel.`);
